def _split_report_params(report: Dict[str, object]) -> Tuple[Dict[str, object], Dict[str, object]]:
    if not isinstance(report, dict):
        return {}, {}
    params = report.get("params")
    if not isinstance(params, dict):
        params = {}
    report_body = {key: value for key, value in report.items() if key != "params"}
    return report_body, params


def _build_metadata(window_metrics_path: Path, topic_file: Path) -> Dict[str, object]:
    category = f"{window_metrics_path.parent.parent.parent.name}/{window_metrics_path.parent.parent.name}"
    text_name = window_metrics_path.parent.name
    return {
        "category": category,
        "text_name": text_name,
        "filename": window_metrics_path.name,
        "topic_file": str(topic_file),
    }


