def _build_dashboard_entry(
    window_metrics_path: Path,
    *,
    report_builder: Callable[..., Dict[str, object]],
    builder_kwargs: Dict[str, object],
) -> Optional[Dict[str, object]]:
    topic_file = find_topic_file(window_metrics_path)
    if not topic_file:
        return None

    window_data = load_window_metrics(window_metrics_path)
    topics_data = load_json(topic_file)
    if not isinstance(topics_data, dict):
        return None

    metadata = _build_metadata(window_metrics_path, topic_file)
    report = report_builder(window_data, topics_data, **builder_kwargs)
    if not report:
        syntax_windows = []
        if isinstance(window_data, dict):
            syntax_payload = window_data.get("syntax", {})
            if isinstance(syntax_payload, dict):
                candidate_windows = syntax_payload.get("windows", [])
                if isinstance(candidate_windows, list):
                    syntax_windows = candidate_windows
        topic_windows = topics_data.get("windows", []) if isinstance(topics_data, dict) else []
        return {
            "metadata": metadata,
            "report": {
                "window_count": len(syntax_windows),
                "metric_names": [],
                "coverage": {
                    "status": "insufficient_topic_signal",
                    "reason": "No aligned topic-presence correlations could be computed for this text.",
                    "topic_window_count": len(topic_windows) if isinstance(topic_windows, list) else 0,
                },
            },
            "params": dict(builder_kwargs),
        }

    report_body, params = _split_report_params(report)
    return {
        "metadata": metadata,
        "report": report_body,
        "params": params,
    }


