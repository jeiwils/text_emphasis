def run_dashboard(
    use_existing: bool = DEFAULT_USE_EXISTING,
    *,
    block_size: int = DEFAULT_BLOCK_SIZE,
    permutations: int = DEFAULT_DASHBOARD_PERMUTATIONS,
    output_root: Optional[Path] = None,
    authors: Optional[List[str]] = None,
    texts: Optional[List[str]] = None,
) -> List[Dict[str, object]]:
    """
    Build topic correlation outputs from window metrics and write JSON outputs.
    Optionally filter by author or text name for targeted runs.

    Outputs (per text):
      data/results/dashboard/<genre>/<author>/<text>/<text>_topic_correlations.json
      data/results/dashboard/<genre>/<author>/<text>/<text>_central_topic_correlations.json
      data/results/dashboard/<genre>/<author>/<text>/<text>_central_topic_presence_correlations.json
      data/results/dashboard/<genre>/<author>/<text>/<text>_topic_presence_correlations.json
      data/results/dashboard/<genre>/<author>/<text>/<text>_non_central_topic_presence_correlations.json
      data/results/dashboard/<genre>/<author>/<text>/<text>_window_variances.json
    Outputs (aggregates):
      data/results/dashboard/<genre>/00_genre_central_topic_presence_correlations.json
    """
    if output_root is None:
        output_root = results_path("dashboard", block_size=block_size)
    output_root = Path(output_root)
    output_root.mkdir(parents=True, exist_ok=True)

    window_metric_files = find_window_metrics_files()
    text_filter = set(texts) if texts else None
    if authors:
        window_metric_files = [
            file for file in window_metric_files if file.parent.parent.name in authors
        ]
    if text_filter:
        window_metric_files = [
            file for file in window_metric_files if file.parent.name in text_filter
        ]
    if not window_metric_files:
        return []

    skip_topic_split_half = False
    skip_all_topic_split_half = False
    skip_presence_split_half = False
    if use_existing:
        genre_author_pairs = {
            (file.parent.parent.parent.name, file.parent.parent.name)
            for file in window_metric_files
        }
        topic_split_half_output_path = output_root / CENTRAL_TOPIC_SPLIT_HALF_FILENAME
        topic_genre_outputs = {
            output_root / genre / GENRE_CENTRAL_TOPIC_SPLIT_HALF_FILENAME
            for genre, _author in genre_author_pairs
        }
        topic_author_outputs = {
            output_root
            / genre
            / author
            / AUTHOR_CENTRAL_TOPIC_SPLIT_HALF_TEMPLATE.format(author=author)
            for genre, author in genre_author_pairs
        }
        skip_topic_split_half = (
            topic_split_half_output_path.exists()
            and all(path.exists() for path in topic_genre_outputs)
            and all(path.exists() for path in topic_author_outputs)
        )
        all_topic_split_half_output_path = output_root / TOPIC_SPLIT_HALF_FILENAME
        all_topic_genre_outputs = {
            output_root / genre / GENRE_TOPIC_SPLIT_HALF_FILENAME
            for genre, _author in genre_author_pairs
        }
        all_topic_author_outputs = {
            output_root
            / genre
            / author
            / AUTHOR_TOPIC_SPLIT_HALF_TEMPLATE.format(author=author)
            for genre, author in genre_author_pairs
        }
        skip_all_topic_split_half = (
            all_topic_split_half_output_path.exists()
            and all(path.exists() for path in all_topic_genre_outputs)
            and all(path.exists() for path in all_topic_author_outputs)
        )
        presence_split_half_output_path = output_root / CENTRAL_PRESENCE_SPLIT_HALF_FILENAME
        presence_genre_outputs = {
            output_root / genre / GENRE_CENTRAL_PRESENCE_SPLIT_HALF_FILENAME
            for genre, _author in genre_author_pairs
        }
        presence_author_outputs = {
            output_root
            / genre
            / author
            / AUTHOR_CENTRAL_PRESENCE_SPLIT_HALF_TEMPLATE.format(author=author)
            for genre, author in genre_author_pairs
        }
        skip_presence_split_half = (
            presence_split_half_output_path.exists()
            and all(path.exists() for path in presence_genre_outputs)
            and all(path.exists() for path in presence_author_outputs)
        )
    central_presence_entries: List[Dict[str, object]] = []
    topic_split_half_entries: List[Dict[str, object]] = []
    split_half_entries: List[Dict[str, object]] = []
    presence_split_half_entries: List[Dict[str, object]] = []

    for file in tqdm(window_metric_files, desc="Dashboard correlations", ascii=True):
        genre = file.parent.parent.parent.name
        author = file.parent.parent.name
        text_name = file.parent.name
        out_dir = output_root / genre / author / text_name
        out_dir.mkdir(parents=True, exist_ok=True)

        topic_file = _report_output_path(out_dir, TOPIC_CORRELATIONS_SUFFIX)
        central_file = _report_output_path(out_dir, CENTRAL_TOPIC_CORRELATIONS_SUFFIX)
        presence_file = _report_output_path(out_dir, CENTRAL_TOPIC_PRESENCE_CORRELATIONS_SUFFIX)
        topic_presence_file = _report_output_path(out_dir, TOPIC_PRESENCE_CORRELATIONS_SUFFIX)
        non_central_presence_file = _report_output_path(
            out_dir,
            NON_CENTRAL_TOPIC_PRESENCE_CORRELATIONS_SUFFIX,
        )
        variance_file = _report_output_path(out_dir, WINDOW_VARIANCE_SUFFIX)

        topic_existing_file = _existing_report_path(out_dir, text_name, TOPIC_CORRELATIONS_SUFFIX)
        central_existing_file = _existing_report_path(out_dir, text_name, CENTRAL_TOPIC_CORRELATIONS_SUFFIX)
        presence_existing_file = _existing_report_path(out_dir, text_name, CENTRAL_TOPIC_PRESENCE_CORRELATIONS_SUFFIX)
        topic_presence_existing_file = _existing_report_path(out_dir, text_name, TOPIC_PRESENCE_CORRELATIONS_SUFFIX)
        non_central_presence_existing_file = _existing_report_path(
            out_dir,
            text_name,
            NON_CENTRAL_TOPIC_PRESENCE_CORRELATIONS_SUFFIX,
        )
        variance_existing_file = _existing_report_path(out_dir, text_name, WINDOW_VARIANCE_SUFFIX)

        topic_entry = None
        if use_existing and topic_existing_file.exists():
            try:
                with open(topic_existing_file, "r", encoding="utf-8") as f:
                    topic_entry = json.load(f)
            except json.JSONDecodeError:
                topic_entry = None
        if topic_entry is None:
            topic_entry = _build_topic_dashboard_entry(
                file,
                block_size=block_size,
                permutations=permutations,
            )
            if topic_entry:
                with open(topic_file, "w", encoding="utf-8") as f:
                    json.dump(topic_entry, f, indent=2)
        if topic_entry and not skip_all_topic_split_half:
            topic_split_half_entry = _build_topic_split_half_entry(
                file,
                topic_entry,
            )
            if topic_split_half_entry:
                topic_split_half_entries.append(topic_split_half_entry)

        central_entry = None
        if use_existing and central_existing_file.exists():
            try:
                with open(central_existing_file, "r", encoding="utf-8") as f:
                    central_entry = json.load(f)
            except json.JSONDecodeError:
                central_entry = None
        if central_entry is None:
            central_entry = _build_central_topic_entry(
                file,
                block_size=block_size,
                permutations=permutations,
            )
        if central_entry:
            with open(central_file, "w", encoding="utf-8") as f:
                json.dump(central_entry, f, indent=2)
            if not skip_topic_split_half:
                split_half_entry = _build_central_topic_split_half_entry(
                    file,
                    central_entry,
                )
                if split_half_entry:
                    split_half_entries.append(split_half_entry)

        topic_presence_entry = None
        if use_existing and topic_presence_existing_file.exists():
            try:
                with open(topic_presence_existing_file, "r", encoding="utf-8") as f:
                    topic_presence_entry = json.load(f)
            except json.JSONDecodeError:
                topic_presence_entry = None
        if topic_presence_entry is None:
            topic_presence_entry = _build_topic_presence_entry(
                file,
                block_size=block_size,
                permutations=permutations,
            )
        if topic_presence_entry:
            with open(topic_presence_file, "w", encoding="utf-8") as f:
                json.dump(topic_presence_entry, f, indent=2)

        non_central_presence_entry = None
        if use_existing and non_central_presence_existing_file.exists():
            try:
                with open(non_central_presence_existing_file, "r", encoding="utf-8") as f:
                    non_central_presence_entry = json.load(f)
            except json.JSONDecodeError:
                non_central_presence_entry = None
        if non_central_presence_entry is None:
            non_central_presence_entry = _build_non_central_presence_entry(
                file,
                block_size=block_size,
                permutations=permutations,
            )
        if non_central_presence_entry:
            with open(non_central_presence_file, "w", encoding="utf-8") as f:
                json.dump(non_central_presence_entry, f, indent=2)

        presence_entry = None
        if use_existing and presence_existing_file.exists():
            try:
                with open(presence_existing_file, "r", encoding="utf-8") as f:
                    presence_entry = json.load(f)
            except json.JSONDecodeError:
                presence_entry = None
        if presence_entry is None:
            presence_entry = _build_central_presence_entry(
                file,
                block_size=block_size,
                permutations=permutations,
            )
        if presence_entry:
            with open(presence_file, "w", encoding="utf-8") as f:
                json.dump(presence_entry, f, indent=2)
            central_presence_entries.append(
                {
                    "category": f"{genre}/{author}",
                    "genre": genre,
                    "author": author,
                    "text_name": text_name,
                    "filename": file.name,
                    "presence_report": presence_entry,
                }
            )
            if not skip_presence_split_half:
                presence_split_half_entry = _build_central_presence_split_half_entry(
                    file,
                    presence_entry,
                )
                if presence_split_half_entry:
                    presence_split_half_entries.append(presence_split_half_entry)

        variance_entry = None
        if use_existing and variance_existing_file.exists():
            try:
                with open(variance_existing_file, "r", encoding="utf-8") as f:
                    variance_entry = json.load(f)
            except json.JSONDecodeError:
                variance_entry = None
        if variance_entry is None:
            window_data = load_window_metrics(file)
            variance_report = build_window_variance_report(window_data)
            if variance_report:
                variance_entry = {
                    "metadata": _build_window_metadata(file),
                    "report": variance_report,
                }
                with open(variance_file, "w", encoding="utf-8") as f:
                    json.dump(variance_entry, f, indent=2)

    _write_genre_central_presence_correlations(
        central_presence_entries,
        use_existing=use_existing,
        output_root=output_root,
    )
    if not skip_all_topic_split_half:
        _write_topic_split_half_summary(
            topic_split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
        _write_genre_topic_split_half_summary(
            topic_split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
        _write_author_topic_split_half_summary(
            topic_split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
    if not skip_topic_split_half:
        _write_central_topic_split_half_summary(
            split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
        _write_genre_central_topic_split_half_summary(
            split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
        _write_author_central_topic_split_half_summary(
            split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
    if not skip_presence_split_half:
        _write_central_presence_split_half_summary(
            presence_split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
        _write_genre_central_presence_split_half_summary(
            presence_split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )
        _write_author_central_presence_split_half_summary(
            presence_split_half_entries,
            use_existing=use_existing,
            output_root=output_root,
        )

    return []

def run_dashboard_with_config(
    use_existing: bool = DEFAULT_USE_EXISTING,
    *,
    authors: Optional[List[str]] = None,
    texts: Optional[List[str]] = None,
    config: DashboardCorrelationConfig = DEFAULT_DASHBOARD_CORRELATION_CONFIG,
) -> List[Dict[str, object]]:
    if config.loop_enabled:
        block_sizes = list(config.loop_block_sizes or ())
        if not block_sizes:
            block_sizes = [config.block_size]
        output_roots: List[Path] = []
        block_labels: List[str] = []
        for block_size in block_sizes:
            output_root = block_results_path(
                "dashboard",
                block_size,
                template=config.loop_output_template,
            )
            output_roots.append(output_root)
            block_labels.append(output_root.name)
            run_dashboard(
                use_existing=use_existing,
                block_size=block_size,
                permutations=config.permutations,
                output_root=output_root,
                authors=authors,
                texts=texts,
            )
        _write_cross_block_consistency_summary(
            output_roots,
            block_labels,
            use_existing=use_existing,
        )
        return []

    return run_dashboard(
        use_existing=use_existing,
        block_size=config.block_size,
        permutations=config.permutations,
        authors=authors,
        texts=texts,
    )

if __name__ == "__main__":
    run_dashboard_with_config()
